import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const iconsDir = path.join(root, 'src/shared/assets/icons');
const indexPath = path.join(iconsDir, 'index.ts');

function toCamelCase(fileName) {
  return fileName
    .replace(/\.svg$/i, '')
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part, idx) => {
      const normalized = part.toLowerCase();
      return idx === 0 ? normalized : normalized.charAt(0).toUpperCase() + normalized.slice(1);
    })
    .join('');
}

const svgFiles = fs
  .readdirSync(iconsDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.svg'))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b));

const seen = new Set();
const exportLines = [];

for (const fileName of svgFiles) {
  const exportName = toCamelCase(fileName);
  if (!exportName) {
    console.error(`Invalid icon file name: ${fileName}`);
    process.exit(1);
  }

  if (seen.has(exportName)) {
    console.error(`Export name collision: ${exportName} (file: ${fileName})`);
    process.exit(1);
  }

  seen.add(exportName);
  exportLines.push(`export { default as ${exportName} } from './${fileName}';`);
}

const header = '// Auto-generated by scripts/sync-icons-index.mjs. Do not edit manually.\n';
const next = `${header}${exportLines.join('\n')}${exportLines.length > 0 ? '\n' : ''}`;
const prev = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, 'utf8') : '';

if (prev === next) {
  console.log('icons index is up to date.');
  process.exit(0);
}

fs.writeFileSync(indexPath, next, 'utf8');
console.log('Updated src/shared/assets/icons/index.ts');
