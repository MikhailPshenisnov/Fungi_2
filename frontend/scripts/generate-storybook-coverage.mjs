import fs from 'node:fs';
import path from 'node:path';
import { collectStorybookCoverage, toRepoRelativePath } from './storybook-coverage-utils.mjs';

const checkMode = process.argv.includes('--check');

function formatPercent(coveredComponents, requiredComponents) {
  if (requiredComponents === 0) {
    return '100.00%';
  }

  return `${((coveredComponents / requiredComponents) * 100).toFixed(2)}%`;
}

function buildSummaryRows(coverage) {
  const rows = coverage.scopes.map((scope) => [
    scope.scopeLabel,
    String(scope.requiredDirectories),
    String(scope.coveredDirectories),
    String(scope.missingDirectories),
    String(scope.requiredComponents),
    String(scope.coveredComponents),
    String(scope.missingComponents),
    formatPercent(scope.coveredComponents, scope.requiredComponents)
  ]);

  rows.push([
    '**Total**',
    String(coverage.totals.requiredDirectories),
    String(coverage.totals.coveredDirectories),
    String(coverage.totals.missingDirectories),
    String(coverage.totals.requiredComponents),
    String(coverage.totals.coveredComponents),
    String(coverage.totals.missingComponents),
    formatPercent(coverage.totals.coveredComponents, coverage.totals.requiredComponents)
  ]);

  return rows;
}

function buildDirectoryRows(coverage) {
  const rows = [];

  for (const scope of coverage.scopes) {
    for (const directory of scope.directories) {
      const coveredComponents = directory.hasStories ? directory.requiredComponents : 0;
      const missingComponents = directory.requiredComponents - coveredComponents;
      const hasStories = directory.hasStories ? 'yes' : 'no';

      rows.push([
        scope.scopeLabel,
        `\`${directory.directoryPathFromRepo}\``,
        hasStories,
        String(directory.requiredComponents),
        String(coveredComponents),
        String(missingComponents),
        formatPercent(coveredComponents, directory.requiredComponents)
      ]);
    }
  }

  return rows;
}

function buildMissingRows(coverage) {
  return coverage.missingItems.map((item) => [
    item.scopeLabel,
    `\`${item.directoryPathFromRepo}\``,
    item.componentPathsFromRepo.map((componentPath) => `\`${componentPath}\``).join('<br>'),
    `\`${item.expectedStoryPathFromRepo}\``
  ]);
}

function appendMarkdownTable(lines, headers, rows) {
  lines.push(`| ${headers.join(' | ')} |`);
  lines.push(`| ${headers.map(() => '---').join(' | ')} |`);

  for (const row of rows) {
    lines.push(`| ${row.join(' | ')} |`);
  }
}

function buildMarkdown(coverage) {
  const lines = [];

  lines.push('# Storybook Coverage');
  lines.push('');
  lines.push('_Auto-generated by `frontend/scripts/generate-storybook-coverage.mjs`._');
  lines.push('');
  lines.push('## Rule');
  lines.push('');
  lines.push('- A Storybook story is required when a `ui` directory contains a TSX component file.');
  lines.push('- Scopes: `src/shared/ui`, `src/pages`, `src/widgets`, `src/features`, `src/entities`.');
  lines.push('- For `src/shared/ui`, requirement is evaluated per component directory inside `primitives` / `composites`.');
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  appendMarkdownTable(
    lines,
    [
      'Scope',
      'Required UI Dirs',
      'Covered UI Dirs',
      'Missing UI Dirs',
      'Required Components',
      'Covered Components',
      'Missing Components',
      'Coverage'
    ],
    buildSummaryRows(coverage)
  );
  lines.push('');

  const missingRows = buildMissingRows(coverage);
  lines.push('## Missing Stories');
  lines.push('');
  if (missingRows.length === 0) {
    lines.push('No missing stories.');
    lines.push('');
  } else {
    appendMarkdownTable(lines, ['Scope', 'UI Directory', 'Components', 'Expected Story'], missingRows);
    lines.push('');
  }

  const directoryRows = buildDirectoryRows(coverage);
  lines.push('## Coverage by Directory');
  lines.push('');
  if (directoryRows.length === 0) {
    lines.push('No UI directories with TSX components were found.');
    lines.push('');
  } else {
    appendMarkdownTable(
      lines,
      ['Scope', 'Directory', 'Has Story', 'Required Components', 'Covered', 'Missing', 'Coverage'],
      directoryRows
    );
    lines.push('');
  }

  return `${lines.join('\n')}`;
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n/g, '\n');
}

const coverage = collectStorybookCoverage();
const outputPath = path.join(coverage.repoRoot, 'docs/frontend/storybook-coverage.md');
const outputPathFromRepo = toRepoRelativePath(coverage.repoRoot, outputPath);
const nextMarkdown = buildMarkdown(coverage);

if (checkMode) {
  if (!fs.existsSync(outputPath)) {
    console.error(`Coverage file is missing: ${outputPathFromRepo}`);
    console.error('Run: npm run stories:coverage');
    process.exit(1);
  }

  const currentMarkdown = fs.readFileSync(outputPath, 'utf8');
  if (normalizeLineEndings(currentMarkdown) !== normalizeLineEndings(nextMarkdown)) {
    console.error(`Coverage file is outdated: ${outputPathFromRepo}`);
    console.error('Run: npm run stories:coverage');
    process.exit(1);
  }

  console.log(`Coverage file is up to date: ${outputPathFromRepo}`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, nextMarkdown, 'utf8');

console.log(`Updated ${outputPathFromRepo}`);
console.log(
  `Coverage: ${coverage.totals.coveredComponents}/${coverage.totals.requiredComponents} components (${formatPercent(
    coverage.totals.coveredComponents,
    coverage.totals.requiredComponents
  )})`
);
console.log(`Missing stories: ${coverage.totals.missingComponents}`);
